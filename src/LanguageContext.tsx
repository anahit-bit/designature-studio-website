export type PortfolioFilter = 'All' | 'Residential' | 'Commercial';

// URL ⇄ page-state mapping. URL is the source of truth; localStorage persistence
// has been removed since the browser address bar now records which page you're on.
function pathToPageState(pathname: string): { page: Page; projectId: string | null } {
  if (pathname === '/' || pathname === '') return { page: 'home', projectId: null };
  if (pathname === '/portfolio') return { page: 'portfolio', projectId: null };
  const projectMatch = pathname.match(/^\/portfolio\/([^/]+)\/?$/);
  if (projectMatch) return { page: 'project-detail', projectId: decodeURIComponent(projectMatch[1]) };
  if (pathname === '/services') return { page: 'services', projectId: null };
  if (pathname === '/studio') return { page: 'studio', projectId: null };
  if (pathname === '/deliverables') return { page: 'deliverables', projectId: null };
  if (pathname === '/ai-concepts') return { page: 'ai-concepts', projectId: null };
  if (pathname === '/ai-vision') return { page: 'ai-vision', projectId: null };
  if (pathname === '/pricing') return { page: 'pricing', projectId: null };
  if (pathname === '/faq') return { page: 'faq', projectId: null };
  if (pathname === '/journal') return { page: 'journal', projectId: null };
  if (/^\/journal\/category\/[^/]+\/?$/.test(pathname)) return { page: 'journal-category', projectId: null };
  if (/^\/journal\/[^/]+\/?$/.test(pathname)) return { page: 'journal-detail', projectId: null };
  if (pathname === '/terms') return { page: 'terms', projectId: null };
  if (pathname === '/privacy') return { page: 'privacy', projectId: null };
  if (pathname === '/refund') return { page: 'refund', projectId: null };
  if (pathname === '/consultation') return { page: 'consultation', projectId: null };
  if (pathname === '/booking/confirmed') return { page: 'booking-confirmed', projectId: null };
  if (pathname === '/booking/failed') return { page: 'booking-failed', projectId: null };
  return { page: 'home', projectId: null };
}

function pageToPath(page: Page, projectId?: string | null, filter?: PortfolioFilter): string {
  switch (page) {
    case 'home':
      return '/';
    case 'portfolio':
      return filter && filter !== 'All' ? `/portfolio?filter=${filter}` : '/portfolio';
    case 'project-detail':
      return projectId ? `/portfolio/${encodeURIComponent(projectId)}` : '/portfolio';
    case 'services':
      return '/services';
    case 'studio':
      return '/studio';
    case 'deliverables':
      return '/deliverables';
    case 'ai-concepts':
      return '/ai-concepts';
    case 'ai-vision':
      return '/ai-vision';
    case 'pricing':
      return '/pricing';
    case 'faq':
      return '/faq';
    case 'journal':
      return '/journal';
    case 'journal-detail':
      return projectId ? `/journal/${encodeURIComponent(projectId)}` : '/journal';
    case 'journal-category':
      return projectId ? `/journal/category/${encodeURIComponent(projectId)}` : '/journal';
    case 'terms':
      return '/terms';
    case 'privacy':
      return '/privacy';
    case 'refund':
      return '/refund';
    case 'consultation':
      return '/consultation';
    case 'booking-confirmed':
      return '/booking/confirmed';
    case 'booking-failed':
      return '/booking/failed';
  }
}

